// 6.0.17 · Writes src/evidence/reviews617.js from the Medieval Lands and DBI reviews (compact form).
import fs from 'node:fs';
const read = path => { const url = new URL(path, import.meta.url); return fs.existsSync(url) ? JSON.parse(fs.readFileSync(url)) : {}; };
const fmg = read('../../../.cache/fmg/reviews617.json'), dbi = read('../../../.cache/dbi/reviews617.json');
const pages = [], titles = [];
const index = (list, value) => { let i = list.indexOf(value); if (i < 0) { list.push(value); i = list.length - 1; } return i; };
const data = {};
for (const [id, review] of Object.entries(fmg)) {
  const s = review.sources[0], [page, anchor = ''] = s.url.replace('https://fmg.ac/Projects/MedLands/', '').split('#');
  const quote = (s.locator.match(/«(.*)»$/) || [])[1] || '';
  const kind = s.locator.startsWith('Lista de hijos') ? 'L' : s.locator.startsWith('Matrimonio') ? 'M' : 'E';
  data[id] = ['f', index(pages, page), anchor, kind, quote, kind === 'L' ? s.locatorEn.match(/^Children of (.*?): “/)[1] : ''];
}
for (const [id, review] of Object.entries(dbi)) {
  const s = review.sources[0], slug = s.url.replace('https://www.treccani.it/enciclopedia/', '').replace('_(Dizionario-Biografico)/', '');
  data[id] = ['d', index(titles, `${slug}|${s.title.replace('Treccani · Dizionario Biografico degli Italiani · ', '')}`), (s.locator.match(/«(.*)»$/) || [])[1] || ''];
}
const body = `// 6.0.17 · Claim reviews from Medieval Lands (Foundation for Medieval Genealogy) and the
// Dizionario Biografico degli Italiani. Medieval Lands entries are identified only when both life years
// and the given name (and regnal number) agree; a relationship is documented when the entry names the
// relative or lists the person among the children of the relative's own identified entry. DBI articles
// document parents named in their opening sentence. Generated by scripts/research/fmg/emit617.mjs.
const PAGES = ${JSON.stringify(pages)};
const DBI = ${JSON.stringify(titles)};
const DATA = ${JSON.stringify(data)};
const WORDS = {birth: ['nacimiento', 'birth'], death: ['fallecimiento', 'death'], father: ['padre', 'father'], mother: ['madre', 'mother'], spouse: ['cónyuge', 'spouse']};
const fmgTitle = page => \`Foundation for Medieval Genealogy · Medieval Lands · \${decodeURIComponent(page).replace(/\\.htm$/, '')}\`;
export const REVIEWS_617 = (() => {
  const out = {};
  for (const [id, row] of Object.entries(DATA)) {
    const kind = id.split(':')[2], [es, en] = WORDS[kind] || ['vínculo', 'relationship'];
    const base = {certainty: 'documented', reviewedAt: '2026-11-22', editor: 'El Árbol de Europa'};
    if (row[0] === 'f') {
      const [, page, anchor, type, quote, parent] = row;
      const locator = type === 'L' ? [\`Lista de hijos de \${parent}: «\${quote}»\`, \`Children of \${parent}: “\${quote}”\`] : type === 'M' ? [\`Matrimonio: «\${quote}»\`, \`Marriage: “\${quote}”\`] : [\`Entrada: «\${quote}»\`, \`Entry: “\${quote}”\`];
      const dates = kind === 'birth' || kind === 'death';
      out[id] = {...base, sources: [{title: fmgTitle(PAGES[page]), url: \`https://fmg.ac/Projects/MedLands/\${PAGES[page]}\${anchor ? \`#\${anchor}\` : ''}\`, locator: locator[0], locatorEn: locator[1]}],
        note: dates ? \`Medieval Lands registra la fecha de \${es}.\` : \`Medieval Lands confirma el vínculo (\${es}).\`, noteEn: dates ? \`Medieval Lands records the date of \${en}.\` : \`Medieval Lands confirms the relationship (\${en}).\`};
    } else {
      const [, title, quote] = row, [slug, name] = DBI[title].split('|');
      out[id] = {...base, sources: [{title: \`Treccani · Dizionario Biografico degli Italiani · \${name}\`, url: \`https://www.treccani.it/enciclopedia/\${slug}_(Dizionario-Biografico)/\`, locator: \`Comienzo del artículo: «\${quote}»\`, locatorEn: \`Opening of the article: “\${quote}”\`}],
        note: \`El Dizionario Biografico degli Italiani confirma el vínculo (\${es}).\`, noteEn: \`The Dizionario Biografico degli Italiani confirms the relationship (\${en}).\`};
    }
  }
  return Object.freeze(out);
})();
`;
const target = new URL('../../../src/evidence/reviews617.js', import.meta.url);
fs.writeFileSync(target, body);
console.log('reviews', Object.keys(data).length, 'bytes', fs.statSync(target).size);
