// 6.0.21 · Writes src/evidence/reviews621.js from the new Medieval Lands reviews (claims not already in
// REVIEWS_617) and the Dizionario Biografico degli Italiani dates and marriages (compact form).
// Usage: node --import ./tests/jsx-loader.mjs scripts/research/fmg/emit621.mjs
import fs from 'node:fs';
const read = path => { const url = new URL(path, import.meta.url); return fs.existsSync(url) ? JSON.parse(fs.readFileSync(url)) : {}; };
const {REVIEWS_617} = await import('../../../src/evidence/reviews617.js');
const fmg = read('../../../.cache/fmg/reviews621.json'), dbi = read('../../../.cache/dbi/reviews621.json');
const pages = [], titles = [];
const index = (list, value) => { let i = list.indexOf(value); if (i < 0) { list.push(value); i = list.length - 1; } return i; };
const toEn = es => es.replace(/^Entrada: «/, 'Entry: “').replace(/^Lista de hijos: «/, 'Children list: “').replace(/^Matrimonio: «/, 'Marriage: “')
  .replace(/ · Matrimonio: «/, ' · Marriage: “').replace(/ · Fallecimiento: /, ' · Death: ').replace(/»/g, '”');
const data = {};
for (const [id, review] of Object.entries(fmg)) {
  if (REVIEWS_617[id]) continue;
  const s = review.sources[0], [page, anchor = ''] = s.url.replace('https://fmg.ac/Projects/MedLands/', '').split('#');
  const child = s.locator.match(/^Lista de hijos de (.*?): «/);
  const row = ['f', index(pages, page), anchor, s.locator];
  if (child) row.push(s.locatorEn.match(/^Children of (.*?): “/)[1]);
  else if (toEn(s.locator) !== s.locatorEn) throw Error(`Locator form: ${id}`);
  data[id] = row;
}
for (const [id, review] of Object.entries(dbi)) {
  const s = review.sources[0], slug = s.url.replace('https://www.treccani.it/enciclopedia/', '').replace('_(Dizionario-Biografico)/', '');
  data[id] = ['d', index(titles, `${slug}|${s.title.replace('Treccani · Dizionario Biografico degli Italiani · ', '')}`), (s.locator.match(/«(.*)»$/) || [])[1] || ''];
}
const body = `// 6.0.21 · Claim reviews from Medieval Lands (Foundation for Medieval Genealogy), third pass, and from
// the full articles of the Dizionario Biografico degli Italiani. Medieval Lands entries are now also
// identified by one sure year and a parent or spouse named in the entry; children lists opened by a
// separate paragraph («King Henry II & his wife had eight children:») document the parents, and the
// office sentences of an entry document governments. Generated by scripts/research/fmg/emit621.mjs.
const PAGES = ${JSON.stringify(pages)};
const DBI = ${JSON.stringify(titles)};
const DATA = ${JSON.stringify(data)};
const WORDS = {birth: ['nacimiento', 'birth'], death: ['fallecimiento', 'death'], father: ['padre', 'father'], mother: ['madre', 'mother'], spouse: ['cónyuge', 'spouse'], government: ['gobierno', 'government']};
const toEn = es => es.replace(/^Entrada: «/, 'Entry: “').replace(/^Lista de hijos: «/, 'Children list: “').replace(/^Matrimonio: «/, 'Marriage: “')
  .replace(/ · Matrimonio: «/, ' · Marriage: “').replace(/ · Fallecimiento: /, ' · Death: ').replace(/»/g, '”');
const fmgTitle = page => \`Foundation for Medieval Genealogy · Medieval Lands · \${decodeURIComponent(page).replace(/\\.htm$/, '')}\`;
export const REVIEWS_621 = (() => {
  const out = {};
  for (const [id, row] of Object.entries(DATA)) {
    const parts = id.split(':'), kind = parts[2], [es, en] = WORDS[kind] || ['vínculo', 'relationship'];
    const base = {certainty: 'documented', reviewedAt: '2026-11-22', editor: 'El Árbol de Europa'};
    const dates = kind === 'birth' || kind === 'death';
    if (row[0] === 'f') {
      const [, page, anchor, locator, parentEn] = row;
      const locatorEn = parentEn ? locator.replace(/^Lista de hijos de .*?: «/, \`Children of \${parentEn}: “\`).replace(/»/g, '”') : toEn(locator);
      const span = kind === 'government' ? \` (\${parts[3]}, \${parts[4]}–\${parts[5]})\` : '';
      out[id] = {...base, sources: [{title: fmgTitle(PAGES[page]), url: \`https://fmg.ac/Projects/MedLands/\${PAGES[page]}\${anchor ? \`#\${anchor}\` : ''}\`, locator, locatorEn}],
        note: dates ? \`Medieval Lands registra la fecha de \${es}.\` : kind === 'government' ? \`Medieval Lands registra el gobierno\${span}.\` : \`Medieval Lands confirma el vínculo (\${es}).\`,
        noteEn: dates ? \`Medieval Lands records the date of \${en}.\` : kind === 'government' ? \`Medieval Lands records the government (\${parts[4]}–\${parts[5]}).\` : \`Medieval Lands confirms the relationship (\${en}).\`};
    } else {
      const [, title, quote] = row, [slug, name] = DBI[title].split('|');
      out[id] = {...base, sources: [{title: \`Treccani · Dizionario Biografico degli Italiani · \${name}\`, url: \`https://www.treccani.it/enciclopedia/\${slug}_(Dizionario-Biografico)/\`, locator: \`Artículo: «\${quote}»\`, locatorEn: \`Article: “\${quote}”\`}],
        note: dates ? \`El Dizionario Biografico degli Italiani registra el año de \${es}.\` : \`El Dizionario Biografico degli Italiani confirma el matrimonio.\`,
        noteEn: dates ? \`The Dizionario Biografico degli Italiani records the year of \${en}.\` : 'The Dizionario Biografico degli Italiani confirms the marriage.'};
    }
  }
  return Object.freeze(out);
})();
`;
const target = new URL('../../../src/evidence/reviews621.js', import.meta.url);
fs.writeFileSync(target, body);
console.log('reviews', Object.keys(data).length, 'bytes', fs.statSync(target).size);
