// 6.0.16 · Writes src/evidence/authorityReviews616.js (compact) and the list of date disagreements.
import fs from 'node:fs';
const {PERSONAS} = await import('../../../src/data/personas.js');
const reviews = JSON.parse(fs.readFileSync('reviews616.json'));
const mismatches = JSON.parse(fs.readFileSync('mismatches616.json'));
const data = {};
const letter = url => url.includes('d-nb.info') ? 'g' : url.includes('bnf.fr') ? 'b' : url.includes('deutsche-biographie') ? 'n' : 'l';
const idOf = url => url.includes('d-nb.info') ? url.split('/gnd/')[1] : url.includes('bnf.fr') ? url.split('/cb')[1] : url.includes('deutsche-biographie') ? url.split('.de/')[1].split('.html')[0] : url.split('/names/')[1].replace('.html', '');
const clause = s => (s.locator.match(/«(.*)»$/) || [])[1] || '';
for (const [claimId, review] of Object.entries(reviews)) {
  const [, id, kind, ...rest] = claimId.split(':');
  const entry = data[id] ||= {};
  for (const s of review.sources) { const k = letter(s.url); entry[k] ||= [idOf(s.url), s.title.split(' · ').slice(k === 'n' ? 1 : 2).join(' · ')]; }
  const letters = review.sources.map(s => letter(s.url)).join('');
  if (kind === 'birth' || kind === 'death') (entry.d ||= {})[kind] = [letters, review.exactDate || +review.note.match(/en (-?\d+)\.$/)[1]];
  else if (kind === 'father' || kind === 'mother' || kind === 'spouse') (entry.r ||= {})[[kind, ...rest].join(':')] = [letters, clause(review.sources.find(s => letter(s.url) === 'b') || {locator: ''}), clause(review.sources.find(s => letter(s.url) === 'n') || {locator: ''})];
  else (entry.v ||= []).push([rest.join(':'), clause(review.sources.find(s => letter(s.url) === 'g') || {locator: ''}), clause(review.sources.find(s => letter(s.url) === 'b') || {locator: ''})]);
}
const header = `// 6.0.16 · Second review against authority records: GND (Deutsche Nationalbibliothek),
// BnF (Bibliothèque nationale de France) and the Library of Congress Name Authority File.
// Wikidata was used only to find each record and is not cited. A pending claim becomes documented
// when a record gives the same year (dates), links the same relative (GND) or names the relative with
// the same years of birth and death in a filiation or marriage clause (BnF), or dates the same office
// and territory with the same years. Disagreements stay pending; see docs/versiones/6.0.16-discrepancias.md.
// Generated by scripts/research/authority-review/run616.mjs; do not edit by hand.
`;
const body = `const DATA = ${JSON.stringify(data)};
const REVIEWED_AT = '2026-11-21';
const EDITOR = 'El Árbol de Europa';
const SOURCE = {
  g: ([id, name]) => ({title: \`Deutsche Nationalbibliothek · Ficha de autoridad GND · \${name}\`, url: \`https://d-nb.info/gnd/\${id}\`}),
  b: ([id, name]) => ({title: \`Bibliothèque nationale de France · Notice d’autorité · \${name}\`, url: \`https://catalogue.bnf.fr/ark:/12148/cb\${id}\`}),
  n: ([id, name]) => ({title: \`Neue Deutsche Biographie · \${name}\`, url: \`https://www.deutsche-biographie.de/\${id}.html#ndbcontent_genealogie\`}),
  l: ([id, name]) => ({title: \`Library of Congress · Name Authority File · \${name}\`, url: \`https://id.loc.gov/authorities/names/\${id}.html\`}),
};
const LABEL = {g: 'GND', b: 'BnF', l: 'Library of Congress', n: 'NDB'};
const review = (sources, note, noteEn, extra = {}) => ({certainty: 'documented', sources, note, noteEn, reviewedAt: REVIEWED_AT, editor: EDITOR, ...extra});
const WORDS = {birth: ['nacimiento', 'birth'], death: ['fallecimiento', 'death'], father: ['padre', 'father'], mother: ['madre', 'mother'], spouse: ['cónyuge', 'spouse']};
export const AUTHORITY_REVIEWS_616 = (() => {
  const out = {};
  for (const [id, entry] of Object.entries(DATA)) {
    const source = (k, locator, locatorEn) => ({...SOURCE[k](entry[k]), locator, locatorEn});
    for (const [kind, [letters, value]] of Object.entries(entry.d || {})) {
      const [es, en] = WORDS[kind], exact = typeof value === 'string' ? value : null, list = [...letters].map(k => LABEL[k]).join(', ');
      out[\`person:\${id}:\${kind}\`] = review([...letters].map(k => k === 'b' ? source(k, 'Ficha de autoridad: fechas codificadas (zona 103)', 'Authority record: coded dates (field 103)') : source(k, \`Datos vitales: fecha de \${es}\`, \`Vital data: date of \${en}\`)),
        \`Las fichas de autoridad (\${list}) registran el \${es} en \${value}.\`, \`The authority records (\${list}) give the \${en} as \${value}.\`, exact ? {exactDate: exact} : {});
    }
    for (const [key, [letters, note, line]] of Object.entries(entry.r || {})) {
      const [es, en] = WORDS[key.split(':')[0]];
      out[\`person:\${id}:\${key}\`] = review([...letters].map(k => k === 'b' ? source(k, \`Nota biográfica: «\${note}»\`, \`Biographical note: “\${note}”\`) : k === 'n' ? source(k, \`Genealogía: «\${line}»\`, \`Genealogy: “\${line}”\`) : source(k, \`Relaciones con personas: \${es}\`, \`Related persons: \${en}\`)),
        letters === 'n' ? \`La Neue Deutsche Biographie confirma el vínculo (\${es}).\` : \`La ficha de autoridad confirma el vínculo (\${es}).\`, letters === 'n' ? \`The Neue Deutsche Biographie confirms the relationship (\${en}).\` : \`The authority record confirms the relationship (\${en}).\`);
    }
    for (const [key, gndClause, bnfClause] of entry.v || []) {
      const [, from, to] = key.split(':');
      const sources = [...(gndClause ? [source('g', \`Datos biográficos: «\${gndClause}»\`, \`Biographical data: “\${gndClause}”\`)] : []), ...(bnfClause ? [source('b', \`Nota biográfica: «\${bnfClause}»\`, \`Biographical note: “\${bnfClause}”\`)] : [])];
      out[\`person:\${id}:government:\${key}\`] = review(sources, \`La ficha de autoridad fecha este cargo en \${from}–\${to}.\`, \`The authority record dates this office to \${from}–\${to}.\`);
    }
  }
  return Object.freeze(out);
})();
// Profile references: authority records consulted for this person in 6.0.16.
export function authorityReferences616(id) {
  const entry = DATA[id];
  return entry ? ['g', 'b', 'n', 'l'].filter(k => entry[k]).map(k => { const s = SOURCE[k](entry[k]); return {titulo: s.title, url: s.url}; }) : [];
}
`;
const target = new URL('../../../src/evidence/authorityReviews616.js', import.meta.url);
fs.writeFileSync(target, header + body);
console.log('people', Object.keys(data).length, 'bytes', fs.statSync(target).size);
const name = Object.fromEntries(PERSONAS.map(p => [p.id, p.nombre]));
const rows = mismatches.map(m => `| ${name[m.id] || m.id} (\`${m.id}\`) | ${m.kind === 'birth' ? 'Nacimiento' : 'Fallecimiento'} | ${m.ours} | ${m.theirs} |`).sort();
fs.writeFileSync(new URL('../../../docs/versiones/6.0.16-discrepancias.md', import.meta.url), `# 6.0.16 · Fechas que no coinciden con las fichas de autoridad

La segunda revisión con fichas de autoridad (GND, BnF y Library of Congress) encontró ${rows.length} fechas
en las que ninguna ficha da el mismo año que el Atlas. No se han cambiado: siguen «Pendientes de revisión»
hasta que una fuente específica permita decidir. Muchas son diferencias de un año propias de las fechas
medievales (estilo del año, fecha de la noticia o cómputo), no necesariamente errores.

| Persona | Dato | Atlas | Fichas |
|---|---|---|---|
${rows.join('\n')}
`);
