// 6.0.16 · Writes the reference works chosen by replace-wikipedia.mjs into the source files.
// Biography references built by helpers (v607, v608, v615 records) are mapped at runtime by
// src/content/reliableReferences616.js, which this script also writes.
import fs from 'node:fs';
const root = new URL('../../../', import.meta.url).pathname;
const choice = JSON.parse(fs.readFileSync(`${root}.cache/reliable-sources/replacements.json`, 'utf8'));
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const subject = old => old.replace(/^Wikipedia(?: en [a-zé]+)? · /, '').replace(/ \(con [^)]*\)$/, '');
const newTitle = (old, entry) => entry.title.split(' · ').length > 1 && !/^(Foundation for Medieval Genealogy|Encyclopaedia Britannica · Georgia)/.test(entry.title) ? entry.title : `${entry.title} · ${subject(old)}`;
const FILES = ['src/content/sources.js', 'src/content/v607People.js', 'src/content/v607Governors.js', 'src/data/stories607/kosciuszko.js', 'src/data/stories607/gustavusAdolphus.js', 'src/cartography/regions/franceLowCountriesRouteData.json',
  ...[1, 2, 3, 4, 5, 6].flatMap(n => ['dynasties', 'territories', 'people', 'stories'].map(kind => `src/features/english/v6/batch-${n}/${kind}.json`))];
let total = 0;
for (const file of FILES) {
  const path = root + file; if (!fs.existsSync(path)) continue;
  let text = fs.readFileSync(path, 'utf8'); const before = text;
  for (const [url, entry] of Object.entries(choice)) {
    if (!text.includes(url)) continue;
    const u = esc(url);
    // {titulo:'…', url:'…'} and "title": "…", "url": "…" in JS or JSON.
    text = text.replace(new RegExp(`((?:titulo|title)["']?\\s*:\\s*)(["'\`])((?:(?!\\2).)*)\\2(\\s*,\\s*["']?url["']?\\s*:\\s*["'\`])${u}(["'\`])`, 'g'),
      (m, key, q, old, mid, q2) => `${key}${q}${newTitle(old, entry).replace(new RegExp(q, 'g'), q === "'" ? '’' : '\\"')}${q}${mid}${entry.url}${q2}`);
    // ref('Wikipedia · …','URL', …) in the story modules.
    text = text.replace(new RegExp(`ref\\('([^']*)','${u}'`, 'g'), (m, old) => `ref('${newTitle(old, entry).replace(/'/g, '’')}','${entry.url}'`);
    // Bare URLs (dynasty source lists and translated copies) keep their registry title.
    text = text.split(url).join(entry.url);
  }
  if (text !== before) { fs.writeFileSync(path, text); total++; console.log('updated', file); }
}
// Dynasty histories: W('Page') helper → the reference work URL.
const housesFile = `${root}src/content/dinastias/casas-v615.js`;
let houses = fs.readFileSync(housesFile, 'utf8');
houses = houses.replace(/W\('([^']+)'\)/g, (m, page) => { const entry = choice[`https://en.wikipedia.org/wiki/${page}`]; if (!entry) throw Error(`No reference work for ${page}`); return `'${entry.url}'`; })
  .replace(/const W = page => `https:\/\/en\.wikipedia\.org\/wiki\/\$\{page\}`;\n/, '');
fs.writeFileSync(housesFile, houses);
// Runtime map for helper-built biography references.
const body = Object.fromEntries(Object.entries(choice).map(([url, entry]) => [url, {url: entry.url, title: entry.title}]));
fs.writeFileSync(`${root}src/content/reliableReferences616.js`, `// 6.0.16 · Wikipedia pages once cited in biographies, mapped to reference works.
// Generated by scripts/research/reliable-sources/apply-wikipedia-replacements.mjs; do not edit by hand.
// Each work was identified through the identifier its Wikidata item records; Wikidata is not cited.
const MAP = ${JSON.stringify(body)};
// Keeps non-Wikipedia references, swaps Wikipedia pages for their reference work and drops pages
// with none. Duplicates collapse to one entry.
export function reliableReferences(refs = [], fallback = []) {
  const out = [];
  for (const ref of refs) {
    const swap = /wikipedia\\.org\\/wiki\\//.test(ref.url) ? MAP[ref.url] : null;
    const value = swap ? {titulo: swap.title.split(' · ').length > 1 ? swap.title : \`\${swap.title} · \${ref.titulo.replace(/^Wikipedia(?: en [a-zé]+)? · /, '').replace(/ \\(con [^)]*\\)$/, '')}\`, url: swap.url} : /wikipedia\\.org/.test(ref.url) ? null : ref;
    if (value && !out.some(item => item.url === value.url)) out.push(value);
  }
  for (const ref of fallback) if (!out.some(item => item.url === ref.url)) out.push(ref);
  return out;
}
`);
console.log('files', total);
