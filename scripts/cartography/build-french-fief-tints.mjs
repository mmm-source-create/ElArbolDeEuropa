import fs from 'node:fs';
import path from 'node:path';
import {projectRoot, mapDataFile} from '../lib/project-paths.mjs';

// Fiefs inside the kingdom share the royal blue family. Neighbouring
// identities must not share a tint, otherwise two duchies would read as one:
// the tints are assigned by greedy colouring of the reviewed cells' contacts.
const TINTS = ['#5B84B1', '#7FA3C7', '#47739C', '#6E8FB8', '#4E91B0', '#3F7AA6',
  '#8DAFCF', '#5D78A8', '#6FA0BF', '#4C6E9E', '#7896C2', '#5598B5'];
const review = JSON.parse(fs.readFileSync(mapDataFile('france-low-countries-full-review.json')));
const early = JSON.parse(fs.readFileSync(mapDataFile('early-medieval-review.json')));
const cells = new Map(JSON.parse(fs.readFileSync(mapDataFile('france-low-countries-geographic-cells.json'))).cells
  .map(cell => [cell.id, cell.bounds]));

const cellsByIdentity = new Map();
for (const phase of [...early.assignments, ...review.assignments]) {
  if (phase.governmentTerritories.includes('Francia')) continue;
  const own = cellsByIdentity.get(phase.identity) || new Set();
  phase.ids.filter(id => cells.has(id)).forEach(id => own.add(id));
  if (own.size) cellsByIdentity.set(phase.identity, own);
}
const touches = (a, b, margin = 0.05) => a[0] <= b[2] + margin && b[0] <= a[2] + margin
  && a[1] <= b[3] + margin && b[1] <= a[3] + margin;
const identities = [...cellsByIdentity.keys()].sort();
const neighbours = new Map(identities.map(identity => [identity, new Set()]));
for (let i = 0; i < identities.length; i += 1) for (let j = i + 1; j < identities.length; j += 1) {
  const [a, b] = [identities[i], identities[j]];
  const contact = [...cellsByIdentity.get(a)].some(x => [...cellsByIdentity.get(b)]
    .some(y => x === y || touches(cells.get(x), cells.get(y))));
  if (contact) { neighbours.get(a).add(b); neighbours.get(b).add(a); }
}
const rgb = hex => [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16));
const distance = (a, b) => Math.hypot(...rgb(a).map((v, i) => v - rgb(b)[i]));
const tints = {};
for (const identity of identities.toSorted((a, b) => neighbours.get(b).size - neighbours.get(a).size || a.localeCompare(b))) {
  const used = [...neighbours.get(identity)].map(n => tints[n]).filter(Boolean);
  // Among the free tints, keep the one farthest from every assigned neighbour.
  const score = tint => (used.includes(tint) ? -1e6 : 0) + Math.min(255, ...used.map(other => distance(tint, other)));
  tints[identity] = TINTS.toSorted((a, b) => score(b) - score(a) || TINTS.indexOf(a) - TINTS.indexOf(b))[0];
}
const clashes = identities.filter(identity => [...neighbours.get(identity)].some(n => tints[n] === tints[identity]));
const sorted = Object.fromEntries(Object.entries(tints).sort(([a], [b]) => a.localeCompare(b, 'es')));
fs.writeFileSync(path.join(projectRoot, 'src/cartography/frenchFiefTints.js'),
  '// Generated by scripts/cartography/build-french-fief-tints.mjs. Do not edit by hand.\n'
  + `export const FRENCH_FIEF_TINTS = Object.freeze(${JSON.stringify(sorted, null, 1)});\n`);
console.log(`Tonos de feudos: ${identities.length} identidades, ${clashes.length} vecinos con el mismo tono.`);
