// 6.0.18 one-off: every English URL built from a machine-translated or broken name moves to the form of
// the reviewed English name (people, dynasties and territories); the old URL redirects (301).
// An address is kept when all its words appear in the English name, nickname, role or aliases
// (for example peter-the-great or richard-neville-earl-of-warwick).
// Usage: node --import ./tests/jsx-loader.mjs scripts/data/fix-english-slugs-618.mjs [--dry]
import fs from 'node:fs';
const root = new URL('../../', import.meta.url);
const DRY = process.argv.includes('--dry');
const {TRANSLATED_PEOPLE, TRANSLATED_DYNASTIES, TRANSLATED_TERRITORIES} = await import('../../src/features/english/routes.js');
const {COMPLETE_ENGLISH_PROFILES} = await import('../../src/features/english/fullProfiles.js');
const {repairEnglishPresentation} = await import('../../src/features/english/nameCorrections.js');
const {ENGLISH_DYNASTIES, ENGLISH_TERRITORIES} = await import('../../src/features/english/entityTranslations.js');
const {slugPublico} = await import('../../src/domain/people/personLabels.js');
const file = new URL('src/data/englishSlugs618.js', root);
// Apostrophes and ʿayn are dropped before building an address (Ma’mun → mamun, O’Donnell → odonnell).
const slug = text => slugPublico(String(text || '').replace(/[’'ʿʾ`´]/g, ''));
const tokens = text => new Set([...slug(text).split('-'), ...slugPublico(String(text || '')).split('-')].filter(Boolean));
const fits = (slug, texts) => { const allowed = new Set(texts.flatMap(t => [...tokens(t)])); return slug.split('-').every(t => allowed.has(t)); };
const result = {people: {}, dynasties: {}, territories: {}};
// People.
const used = new Set(TRANSLATED_PEOPLE.map(r => r.en));
for (const route of TRANSLATED_PEOPLE) {
  const profile = repairEnglishPresentation(COMPLETE_ENGLISH_PROFILES[route.id] || {});
  if (!profile?.name) continue;
  const suffix = `-${slugPublico(route.id)}`, base = route.en.endsWith(suffix) ? route.en.slice(0, -suffix.length) : route.en;
  // The name followed by a distinguishing title (richard-neville-earl-of-salisbury) is a good address.
  if ([slug(profile.name), slugPublico(profile.name)].some(good => base === good || base.startsWith(`${good}-`))) continue;
  if (fits(base, [profile.name, profile.nickname, profile.role, ...(profile.aliases || [])])) continue;
  let next = slug(profile.name);
  if (used.has(next)) next += suffix;
  if (used.has(next) || next === route.en) continue;
  used.add(next); result.people[route.id] = {en: next, enBefore: route.en};
}
// Dynasties and territories, keyed by their Spanish slug.
for (const [kind, routes, entities] of [['dynasties', TRANSLATED_DYNASTIES, ENGLISH_DYNASTIES], ['territories', TRANSLATED_TERRITORIES, ENGLISH_TERRITORIES]]) {
  const taken = new Set(routes.map(r => r.en));
  for (const route of routes) {
    const entity = entities.find(e => e.es === route.es);
    if (!entity?.name || route.en === slug(entity.name) || route.en === slugPublico(entity.name) || fits(route.en, [entity.name])) continue;
    const next = slug(entity.name);
    if (!next || taken.has(next)) continue;
    taken.add(next); result[kind][route.es] = {en: next, enBefore: route.en};
  }
}
const counts = Object.fromEntries(Object.entries(result).map(([k, v]) => [k, Object.keys(v).length]));
console.log(counts);
for (const [kind, map] of Object.entries(result)) console.log(kind, Object.values(map).map(v => `${v.enBefore} → ${v.en}`).join('\n  '));
if (DRY) process.exit(0);
fs.writeFileSync(file, `// Generated by scripts/data/fix-english-slugs-618.mjs. English URLs built from machine-translated names,\n// before and after 6.0.18; the old ones redirect. People are keyed by ID, dynasties and territories by Spanish slug.\nexport const ENGLISH_SLUGS_618 = ${JSON.stringify(result, null, 1)};\n`);
let text = fs.readFileSync(new URL('routes.json', root), 'utf8');
const sources = new Set(JSON.parse(text).redirects.map(rule => rule.source));
const segment = {people: 'person', dynasties: 'dynasty', territories: 'territory'};
const lines = Object.entries(result).flatMap(([kind, map]) => Object.values(map).filter(({enBefore}) => !sources.has(`/en/${segment[kind]}/${enBefore}`))
  .map(({en, enBefore}) => `    {"source":"/en/${segment[kind]}/${enBefore}","destination":"/en/${segment[kind]}/${en}","permanent":true,"workerFirst":false},`));
const anchor = text.indexOf('  "redirects": [\n') + '  "redirects": [\n'.length;
text = text.slice(0, anchor) + lines.join('\n') + '\n' + text.slice(anchor);
for (const [kind, map] of Object.entries(result)) for (const {en, enBefore} of Object.values(map)) text = text.replaceAll(`"destination":"/en/${segment[kind]}/${enBefore}"`, `"destination":"/en/${segment[kind]}/${en}"`);
JSON.parse(text);
fs.writeFileSync(new URL('routes.json', root), text);
console.log('redirects added', lines.length);
