// 6.0.16 one-off: English person URLs built from machine-translated names (for example
// /en/person/section-3 for James III of Scotland) move to the corrected name; the old URL redirects.
// Writes src/data/englishSlugs616.js and adds permanent redirects to routes.json.
import fs from 'node:fs';
const root = new URL('../../', import.meta.url);
const {TRANSLATED_PEOPLE} = await import('../../src/features/english/routes.js');
const {ENGLISH_NAME_CORRECTIONS} = await import('../../src/features/english/nameCorrections.js');
const {slugPublico} = await import('../../src/domain/people/personLabels.js');
const file = new URL('src/data/englishSlugs616.js', root);
if (fs.readFileSync(file, 'utf8').includes('"enBefore"')) throw Error('Already applied');
const used = new Set(TRANSLATED_PEOPLE.map(route => route.en));
const bySlug = new Map(Object.entries(ENGLISH_NAME_CORRECTIONS).map(([bad, good]) => [slugPublico(bad), good]));
const slugs = {};
for (const route of TRANSLATED_PEOPLE) {
  const suffix = `-${slugPublico(route.id)}`, base = route.en.endsWith(suffix) ? route.en.slice(0, -suffix.length) : route.en;
  const good = bySlug.get(base);
  if (!good) continue;
  let ideal = slugPublico(good);
  if (ideal === base) continue;
  if (route.en !== base || used.has(ideal)) ideal += suffix;
  if (used.has(ideal)) continue;
  used.add(ideal);
  slugs[route.id] = {en: ideal, enBefore: route.en};
}
fs.writeFileSync(file, `// Generated by scripts/data/fix-english-slugs-616.mjs. English person URLs before and after 6.0.16.\nexport const ENGLISH_SLUGS_616 = ${JSON.stringify(slugs, null, 1)};\n`);
// routes.json keeps its hand formatting: one compact line per new redirect, after the 6.0.9 block.
let text = fs.readFileSync(new URL('routes.json', root), 'utf8');
const config = JSON.parse(text);
const sources = new Set(config.redirects.map(rule => rule.source));
const lines = Object.values(slugs).filter(({enBefore}) => !sources.has(`/en/person/${enBefore}`))
  .map(({en, enBefore}) => `    {"source":"/en/person/${enBefore}","destination":"/en/person/${en}","permanent":true,"workerFirst":false},`);
const anchor = text.indexOf('  "redirects": [\n') + '  "redirects": [\n'.length;
text = text.slice(0, anchor) + lines.join('\n') + '\n' + text.slice(anchor);
// Earlier redirects that pointed at a renamed URL now point straight at the new one.
for (const {en, enBefore} of Object.values(slugs)) text = text.replaceAll(`"destination":"/en/person/${enBefore}"`, `"destination":"/en/person/${en}"`).replaceAll(`"destination": "/en/person/${enBefore}"`, `"destination": "/en/person/${en}"`);
JSON.parse(text);
fs.writeFileSync(new URL('routes.json', root), text);
console.log(Object.keys(slugs).length, 'English URLs corrected');
