// 6.0.9 one-off: removes titles from public names (src/data/titleNames609.js),
// keeps the old names as search variants, fixes the new URLs and writes
// permanent redirects from the published ones. Run once, then `npm run prebuild`.
import fs from 'node:fs';
import {PERSONAS} from '../../src/data/personas.js';
import {TITLE_NAMES_609} from '../../src/data/titleNames609.js';
import {PERSONA_SLUG_POR_ID, slugPersonaPorLocale} from '../../src/features/atlas/atlasRoutes.js';
import {slugPublico} from '../../src/domain/people/personLabels.js';
import runtime from '../../src/generated/englishProfilesRuntime.json' with {type:'json'};

const root = new URL('../../', import.meta.url);
const byId = new Map(PERSONAS.map(p => [p.id, p]));
const enName = id => runtime.profiles[id]?.name;
const enSlugBase = id => slugPublico(runtime.profiles[id].slugName || runtime.profiles[id].name);

// Bases after the change, to detect new homonyms.
const esBase = new Map(PERSONAS.map(p => [p.id, slugPublico(p.slug || p.nombre)]));
const enBase = new Map(Object.keys(runtime.profiles).filter(id => byId.has(id)).map(id => [id, enSlugBase(id)]));
for (const [id, es, en] of TITLE_NAMES_609) {
  const p = byId.get(id);
  if (!p) throw new Error(`Unknown id ${id}`);
  if (es && !p.slug) esBase.set(id, slugPublico(es));
  if (en) { if (!enName(id)) throw new Error(`No English profile ${id}`); enBase.set(id, slugPublico(en)); }
}
const count = map => [...map.values()].reduce((acc, b) => (acc[b] = (acc[b] || 0) + 1, acc), {});
const esCount = count(esBase), enCount = count(enBase);

const slugs = {};
const redirects = [];
for (const [id, es, en, extra = {}] of TITLE_NAMES_609) {
  const p = byId.get(id);
  const entry = slugs[id] = {};
  if (es) {
    const before = PERSONA_SLUG_POR_ID[id];
    const base = esBase.get(id);
    const after = p.slug ? before : esCount[base] > 1 ? `${base}-${slugPublico(id)}` : base;
    Object.assign(entry, {es: after, esBefore: before, nombreBefore: p.nombre});
    if (after !== before) redirects.push([`/es/persona/${before}`, `/es/persona/${after}`]);
  }
  if (en) {
    const before = slugPersonaPorLocale(p, 'en');
    const base = enBase.get(id);
    const after = enCount[base] > 1 ? `${base}-${slugPublico(id)}` : base;
    Object.assign(entry, {en: after, enBefore: before, nameBefore: enName(id), name: en});
    if (after !== before) redirects.push([`/en/person/${before}`, `/en/person/${after}`]);
  }
  if (extra.nickname) entry.nickname = extra.nickname;
}

// personas.js: one JSON record per line.
const personasUrl = new URL('src/data/personas.js', root);
const lines = fs.readFileSync(personasUrl, 'utf8').split('\n');
const changes = new Map(TITLE_NAMES_609.filter(([, es]) => es).map(([id, es, , extra = {}]) => [id, {es, extra}]));
for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(/^  (\{"id":"([^"]+)".*\}),$/);
  if (!m || !changes.has(m[2])) continue;
  const record = JSON.parse(m[1]);
  const {es, extra} = changes.get(m[2]);
  const old = record.nombre;
  record.nombre = es;
  record.aliases = [...new Set([...(record.aliases || []), old])];
  if (extra.sobrenombre) record.sobrenombre = extra.sobrenombre;
  record.slug = slugs[m[2]].es;
  lines[i] = `  ${JSON.stringify(record)},`;
  changes.delete(m[2]);
}
if (changes.size) throw new Error(`Not updated: ${[...changes.keys()]}`);
fs.writeFileSync(personasUrl, lines.join('\n'));

fs.writeFileSync(new URL('src/data/titleNameSlugs609.js', root),
  `// Generated by scripts/data/apply-title-names-609.mjs. Published URLs before and after 6.0.9.\nexport const TITLE_NAME_SLUGS_609 = ${JSON.stringify(slugs, null, 1)};\n`);

// Redirects: routes.json and the Worker-first list in wrangler.jsonc.
const routesUrl = new URL('routes.json', root);
let routes = fs.readFileSync(routesUrl, 'utf8');
const anchor = '    {"source":"/es/persona/galeazzo-ii-visconti-galeazzo2visc","destination":"/es/persona/galeazzo-ii-visconti","permanent":true},\n';
if (!routes.includes(anchor)) throw new Error('routes.json anchor');
routes = routes.replace(anchor, anchor + redirects.map(([s, d]) => `    {"source":${JSON.stringify(s)},"destination":${JSON.stringify(d)},"permanent":true},\n`).join(''));
fs.writeFileSync(routesUrl, routes);

const wranglerUrl = new URL('wrangler.jsonc', root);
let wrangler = fs.readFileSync(wranglerUrl, 'utf8');
const wAnchor = '      "/es/persona/galeazzo-ii-visconti-galeazzo2visc",\n';
if (!wrangler.includes(wAnchor)) throw new Error('wrangler anchor');
wrangler = wrangler.replace(wAnchor, wAnchor + redirects.map(([s]) => `      ${JSON.stringify(s)},\n`).join(''));
fs.writeFileSync(wranglerUrl, wrangler);

console.log(`${TITLE_NAMES_609.length} people, ${redirects.length} redirects`);
