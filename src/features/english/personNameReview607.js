const TITLE_NAMES_609=Object.fromEntries(Object.entries(TITLE_NAME_SLUGS_609).filter(([,s])=>s.en));
const reviewTitleName=(id,profile)=>{
  const review=TITLE_NAMES_609[id];
  if(!review)return profile;
  const aliases=[...new Set([...(profile.aliases||[]),review.nameBefore])];
  return {...profile,name:review.name,slugName:review.en,aliases,...(review.nickname?{nickname:review.nickname}:{})};
};
export const reviewPersonProfiles=profiles=>Object.fromEntries(Object.entries(profiles).map(([id,profile])=>{
  const review=PERSON_NAMES_607[id];
  if(!review)return [id,reviewTitleName(id,profile)];
  const aliases=[...new Set([...(profile.aliases||[]),...(review.aliases||[])])];
  // Published English URLs keep the slug of the name they were created with.
  const slugName=review.name&&review.name!==profile.name?profile.slugName||profile.name:profile.slugName;
  return [id,reviewTitleName(id,{...profile,...review,aliases,...(slugName?{slugName}:{})})];
}));
export const reviewPersonNames=names=>Object.fromEntries(Object.entries(names).map(([id,name])=>[id,TITLE_NAMES_609[id]?.name||PERSON_NAMES_607[id]?.name||name]));
